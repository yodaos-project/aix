pub(crate) const REF_DIR: &str = "__aix_asset_refs/";
const OBJECT_LIMIT: usize = 32 * 1024 * 1024;

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Reference {
    pub path: String,
    pub line: usize,
    pub column: usize,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ProgressiveAssetCandidate {
    pub id: String,
    pub kind: AssetKind,
    pub source_path: String,
    pub source_sha256: String,
    pub source_size: usize,
    pub references: Vec<Reference>,
    pub format: String,
    pub dependencies: Vec<String>,
    pub progressive_support: Support,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Support {
    pub supported: bool,
    pub profile: Option<&'static str>,
    pub required_capabilities: Vec<&'static str>,
    pub features: Vec<&'static str>,
    pub reason: Option<String>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ProgressiveAssetPlan {
    pub id: String,
    pub asset_version: String,
    pub profile: String,
    pub local_metadata: BTreeMap<String, Content>,
    pub layout: TimelineLayout,
    pub remote_objects: Vec<RemoteObject>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct RemoteObject {
    pub id: String,
    pub size: u64,
    pub sha256: String,
    #[serde(serialize_with = "serialize_bytes")]
    pub bytes: Arc<[u8]>,
}

fn serialize_bytes<S: serde::Serializer>(bytes: &[u8], serializer: S) -> Result<S::Ok, S::Error> {
    serde_bytes::serialize(bytes, serializer)
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct ProgressiveAssetUploadReceipt {
    pub upload_id: String,
    pub asset_version: String,
    pub objects: Vec<UploadedObject>,
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct UploadedObject {
    pub id: String,
    pub size: u64,
    pub sha256: String,
    pub url: String,
}

#[derive(Debug, Deserialize)]
#[serde(
    tag = "delivery",
    rename_all = "snake_case",
    rename_all_fields = "camelCase",
    deny_unknown_fields
)]
pub enum Decision {
    Embedded,
    Progressive {
        plan_id: String,
        receipt: ProgressiveAssetUploadReceipt,
    },
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct DeliveryReport {
    pub id: String,
    pub kind: AssetKind,
    pub source_path: String,
    pub delivery: &'static str,
    pub asset_version: Option<String>,
    pub retained_source_bytes: u64,
}

struct Prepared {
    plan: ProgressiveAssetPlan,
    profile: Profile,
    local_name: String,
    local_bytes: Vec<u8>,
}

/// Owns the immutable source snapshot. A plan is memoized in the session;
/// only the receipt and plan ID are accepted back from the caller.
pub struct ProgressivePack {
    files: BTreeMap<String, Arc<[u8]>>,
    candidates: BTreeMap<String, ProgressiveAssetCandidate>,
    ordinary: BTreeSet<String>,
    prepared: BTreeMap<String, Prepared>,
}

impl ProgressivePack {
    pub fn discover(files: Vec<InputFile>) -> Result<Self> {
        let mut files = files;
        files.sort_by(|a, b| a.path.cmp(&b.path));
        crate::validate_paths(&files)?;
        for file in &files {
            if file.path == "VERSION" {
                bail!("VERSION is generated by the packer");
            }
            if file.path.starts_with(PREFIX) || file.path.starts_with(REF_DIR) {
                bail!("generated package path: {}", file.path);
            }
        }
        let mut files: BTreeMap<String, Arc<[u8]>> = files
            .into_iter()
            .map(|file| (file.path, file.data.into()))
            .collect();
        let mut declarations = Vec::new();
        let mut ordinary = BTreeSet::new();
        let mut source_text = BTreeMap::new();
        for (path, data) in &files {
            if !(path.ends_with(".js") || path.ends_with(".ts") || path.ends_with(".ink")) {
                continue;
            }
            let (bytes, _) = crate::normalize_text_to_utf8(path, data)?;
            let source = String::from_utf8(bytes)?;
            let start = declarations.len();
            imports::scan(path, &source, &mut declarations, &mut ordinary)?;
            if declarations.len() > start {
                source_text.insert(path.clone(), source);
            }
        }

        let mut candidates = BTreeMap::<String, ProgressiveAssetCandidate>::new();
        let mut replacements = BTreeMap::<String, Vec<_>>::new();
        for decl in declarations {
            let id = sha256(&serde_json::to_vec(&(&decl.source_path, decl.kind))?);
            let file = decl.reference.path.clone();
            let module = format!("{REF_DIR}{id}.js");
            let parents = file.bytes().filter(|&b| b == b'/').count();
            let specifier = if parents == 0 {
                format!("./{module}")
            } else {
                format!("{}{module}", "../".repeat(parents))
            };
            let specifier = serde_json::to_string(&specifier)?;
            let replacement = if decl.dynamic {
                format!("import({specifier})")
            } else {
                specifier
            };
            replacements
                .entry(file)
                .or_default()
                .push((decl.replacement, replacement));
            if let Some(candidate) = candidates.get_mut(&id) {
                candidate.references.push(decl.reference);
                continue;
            }
            let data = files.get(&decl.source_path).ok_or_else(|| {
                anyhow!(
                    "{}:{}:{}: missing progressive source '{}'",
                    decl.reference.path,
                    decl.reference.line,
                    decl.reference.column,
                    decl.source_path
                )
            })?;
            let format = decl
                .source_path
                .rsplit('.')
                .next()
                .unwrap_or_default()
                .to_ascii_lowercase();
            let support = media::probe(data, decl.kind);
            candidates.insert(
                id.clone(),
                ProgressiveAssetCandidate {
                    id,
                    kind: decl.kind,
                    source_path: decl.source_path,
                    source_sha256: sha256(data),
                    source_size: data.len(),
                    references: vec![decl.reference],
                    format,
                    dependencies: Vec::new(),
                    progressive_support: support,
                },
            );
        }
        for (file, mut changes) in replacements {
            let mut text = source_text.remove(&file).expect("source snapshot exists");
            changes.sort_unstable_by_key(|(range, _)| std::cmp::Reverse(range.start));
            for (range, replacement) in changes {
                text.replace_range(range, &replacement);
            }
            files.insert(file, Arc::from(text.into_bytes()));
        }
        for id in candidates.keys() {
            files.insert(
                format!("{REF_DIR}{id}.js"),
                Arc::from(format!("export default 'aix-asset:{id}';").into_bytes()),
            );
        }
        Ok(Self {
            files,
            candidates,
            ordinary,
            prepared: BTreeMap::new(),
        })
    }

    pub fn candidates(&self) -> Vec<&ProgressiveAssetCandidate> {
        self.candidates.values().collect()
    }

    pub fn prepare(&mut self, id: &str) -> Result<&ProgressiveAssetPlan> {
        if !self.prepared.contains_key(id) {
            let candidate = self
                .candidates
                .get(id)
                .ok_or_else(|| anyhow!("unknown asset candidate"))?;
            if !candidate.progressive_support.supported {
                bail!(
                    "{}: {}",
                    candidate.source_path,
                    candidate
                        .progressive_support
                        .reason
                        .as_deref()
                        .unwrap_or("unsupported profile")
                );
            }
            let (local_name, local_bytes, layout, objects) =
                media::prepare(&self.files[&candidate.source_path], candidate.kind)?;
            let profile_name = candidate
                .progressive_support
                .profile
                .ok_or_else(|| anyhow!("missing prepared profile"))?;
            let profile = Profile {
                profile: profile_name.into(),
                required_capabilities: vec![profile_name.into()],
                local_metadata: BTreeMap::from([(local_name.clone(), identity(&local_bytes))]),
                objects: objects
                    .iter()
                    .map(|(id, bytes)| {
                        (
                            id.clone(),
                            Content {
                                size: bytes.len() as u64,
                                sha256: id.clone(),
                            },
                        )
                    })
                    .collect(),
                layout,
            };
            let asset_version = sha256(&profile.canonical_bytes()?);
            let plan = ProgressiveAssetPlan {
                id: sha256(&serde_json::to_vec(&(id, &asset_version))?),
                asset_version,
                profile: profile.profile.clone(),
                local_metadata: profile.local_metadata.clone(),
                layout: profile.layout.clone(),
                remote_objects: objects
                    .into_iter()
                    .map(|(id, bytes)| RemoteObject {
                        sha256: id.clone(),
                        id,
                        size: bytes.len() as u64,
                        bytes,
                    })
                    .collect(),
            };
            self.prepared.insert(
                id.to_owned(),
                Prepared {
                    plan,
                    profile,
                    local_name,
                    local_bytes,
                },
            );
        }
        Ok(&self.prepared[id].plan)
    }

    pub fn finalize(
        self,
        decisions: BTreeMap<String, Decision>,
        options: PackOptions<'_>,
        progress: impl FnMut(PackProgressEvent) -> Result<()>,
    ) -> Result<PackOutput> {
        let mut files = self.files;
        if decisions.keys().any(|id| !self.candidates.contains_key(id)) {
            bail!("decision supplied for an unknown asset");
        }
        let mut index = Index {
            schema_version: SCHEMA_VERSION,
            assets: BTreeMap::new(),
        };
        let mut omit = BTreeSet::new();
        let mut keep = self.ordinary;
        let mut report = Vec::new();
        for (id, candidate) in self.candidates {
            let (entry, version) = match decisions.get(&id).unwrap_or(&Decision::Embedded) {
                Decision::Embedded => {
                    keep.insert(candidate.source_path.clone());
                    keep.extend(candidate.dependencies.iter().cloned());
                    (
                        IndexEntry::Embedded {
                            kind: candidate.kind,
                            path: candidate.source_path.clone(),
                        },
                        None,
                    )
                }
                Decision::Progressive { plan_id, receipt } => {
                    let prepared = self
                        .prepared
                        .get(&id)
                        .ok_or_else(|| anyhow!("progressive decision has no prepared plan"))?;
                    let locators = verify_receipt(prepared, plan_id, receipt)?;
                    let version = prepared.plan.asset_version.clone();
                    let descriptor = Descriptor {
                        schema_version: SCHEMA_VERSION,
                        asset_version: version.clone(),
                        kind: candidate.kind,
                        delivery: "progressive".into(),
                        profile: prepared.profile.clone(),
                        locators,
                    };
                    let bytes = serde_json::to_vec(&descriptor)?;
                    let digest = sha256(&bytes);
                    let path = format!("{PREFIX}{version}/asset.json");
                    if files
                        .get(&path)
                        .is_some_and(|previous| previous.as_ref() != bytes)
                    {
                        bail!("conflicting receipts for asset version {version}");
                    }
                    files.insert(path.clone(), bytes.into());
                    files.insert(
                        format!("{PREFIX}{version}/{}", prepared.local_name),
                        prepared.local_bytes.clone().into(),
                    );
                    omit.insert(candidate.source_path.clone());
                    omit.extend(candidate.dependencies.iter().cloned());
                    (
                        IndexEntry::Progressive {
                            kind: candidate.kind,
                            path,
                            sha256: digest,
                        },
                        Some(version),
                    )
                }
            };
            report.push((candidate, version));
            index.assets.insert(id, entry);
        }
        let report = report
            .into_iter()
            .map(|(candidate, version)| {
                let retained_source_bytes = std::iter::once(&candidate.source_path)
                    .chain(&candidate.dependencies)
                    .filter(|path| !omit.contains(*path) || keep.contains(*path))
                    .map(|path| files[path].len() as u64)
                    .sum();
                DeliveryReport {
                    id: candidate.id,
                    kind: candidate.kind,
                    source_path: candidate.source_path,
                    delivery: if version.is_some() {
                        "progressive"
                    } else {
                        "embedded"
                    },
                    asset_version: version,
                    retained_source_bytes,
                }
            })
            .collect();
        files.retain(|path, _| !omit.contains(path) || keep.contains(path));
        if !index.assets.is_empty() {
            files.insert(INDEX_PATH.into(), serde_json::to_vec(&index)?.into());
        }
        let entries = files
            .into_iter()
            .map(|(path, bytes)| InputFile::new(path, bytes.to_vec()))
            .collect();
        let mut output = crate::pack_finalized(entries, options, progress)?;
        output.progressive_assets = report;
        Ok(output)
    }
}

fn verify_receipt(
    prepared: &Prepared,
    plan_id: &str,
    receipt: &ProgressiveAssetUploadReceipt,
) -> Result<BTreeMap<String, RemoteLocator>> {
    if plan_id != prepared.plan.id
        || receipt.asset_version != prepared.plan.asset_version
        || receipt.upload_id.trim().is_empty()
    {
        bail!("upload receipt does not match the prepared plan");
    }
    let mut locators = BTreeMap::new();
    for object in &receipt.objects {
        let expected = prepared
            .profile
            .objects
            .get(&object.id)
            .ok_or_else(|| anyhow!("unexpected upload receipt object"))?;
        if expected.sha256 != object.sha256 || expected.size != object.size {
            bail!("upload receipt object length or hash mismatch");
        }
        let url = url::Url::parse(&object.url).map_err(|_| anyhow!("invalid upload locator"))?;
        if url.scheme() != "https"
            || !url.has_host()
            || !url.username().is_empty()
            || url.password().is_some()
            || url.query().is_some()
            || url.fragment().is_some()
        {
            bail!("upload locators must be immutable HTTPS addresses without credentials, query or fragment");
        }
        if locators
            .insert(object.id.clone(), RemoteLocator { url: url.into() })
            .is_some()
        {
            bail!("duplicate upload receipt object");
        }
    }
    if locators.len() != prepared.profile.objects.len() {
        bail!("missing upload receipt objects");
    }
    Ok(locators)
}

fn identity(bytes: &[u8]) -> Content {
    Content {
        size: bytes.len() as u64,
        sha256: sha256(bytes),
    }
}

fn resolve_path(owner: &str, uri: &str) -> Result<String> {
    let decoded = percent_encoding::percent_decode_str(uri).decode_utf8()?;
    if decoded.is_empty()
        || decoded.starts_with('/')
        || decoded.contains([':', '\\', '?', '#', '\0'])
    {
        bail!("unsupported local resource URI");
    }
    let (directory, _) = owner.rsplit_once('/').unwrap_or(("", owner));
    let mut parts: Vec<_> = directory.split('/').filter(|p| !p.is_empty()).collect();
    for part in decoded.split('/') {
        match part {
            "." => {}
            ".." => {
                parts
                    .pop()
                    .ok_or_else(|| anyhow!("resource escapes the package root"))?;
            }
            "" => bail!("empty resource path segment"),
            _ => parts.push(part),
        }
    }
    if parts.is_empty() {
        bail!("resource path is empty");
    }
    let path = parts.join("/");
    if path.starts_with("META-INF/") || path.starts_with(REF_DIR) {
        bail!("resource points to generated metadata");
    }
    Ok(path)
}
