const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const resolve = (name) => require.resolve(name, { paths: [root, path.resolve(root, '../../packages/cli')] });

/** Build the same self-contained, filesystem-free checker for both consumers. */
function writeEnvironment() {
  const tsRoot = path.dirname(resolve('typescript/package.json'));
  const environment = {};
  for (const file of fs.readdirSync(path.join(tsRoot, 'lib')).sort()) {
    if (/^lib.*\.d\.ts$/.test(file)) {
      environment[`/__aix__/typescript/${file}`] = fs.readFileSync(path.join(tsRoot, 'lib', file), 'utf8');
    }
  }
  fs.writeFileSync(path.join(root, 'ts/check/environment.generated.ts'),
    `// Generated by scripts/build-check.js.\nconst environment: Record<string, string> = ${JSON.stringify(environment)};\nexport default environment;\n`);
  return { tsRoot };
}

async function buildCheck(outfile, format = 'esm') {
  const { build } = require(resolve('esbuild'));
  const { tsRoot } = writeEnvironment();
  await build({
    entryPoints: [path.join(root, 'ts/check/index.ts')],
    outfile,
    bundle: true,
    format,
    platform: 'browser',
    target: 'es2020',
    // Disable TypeScript's optional Node system. Our CompilerHost supplies all
    // input and library files; no process/require polyfills are needed in a browser.
    define: { process: 'undefined', require: 'undefined' },
    minifySyntax: true,
    legalComments: 'eof',
    nodePaths: [path.join(root, 'node_modules'), path.resolve(root, '../../packages/cli/node_modules')],
  });
  fs.writeFileSync(`${outfile}.LICENSE.txt`,
    fs.readFileSync(path.join(tsRoot, 'LICENSE.txt'), 'utf8') + '\n' +
    fs.readFileSync(path.join(tsRoot, 'ThirdPartyNoticeText.txt'), 'utf8'));
}

module.exports = { buildCheck, writeEnvironment };
